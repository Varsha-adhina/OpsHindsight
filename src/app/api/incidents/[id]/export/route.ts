import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/db";

export async function GET(
  _req: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  const { id } = await params;
  const incident = await prisma.incident.findUnique({
    where: { id },
    include: {
      events: { orderBy: { timestamp: "asc" } },
      analyses: { orderBy: { createdAt: "desc" }, take: 1 },
      resolution: true,
      memoryOps: { orderBy: { createdAt: "asc" } },
    },
  });
  if (!incident) {
    return NextResponse.json({ error: "Not found" }, { status: 404 });
  }

  let analysis: Record<string, unknown> | null = null;
  if (incident.analyses[0]) {
    try {
      analysis = JSON.parse(incident.analyses[0].responseJson);
    } catch { /* */ }
  }

  const withMem =
    analysis && "withMemory" in analysis
      ? (analysis.withMemory as { response?: Record<string, unknown> })?.response
      : analysis;

  const lines = [
    "OpsHindsight Post-Mortem Report",
    "=".repeat(40),
    `Incident ID: ${incident.externalId}`,
    `Title: ${incident.title}`,
    `Service: ${incident.service}`,
    `Severity: ${incident.severity}`,
    `Environment: ${incident.environment}`,
    `Status: ${incident.status}`,
    `Started: ${incident.startedAt.toISOString()}`,
    incident.resolvedAt ? `Resolved: ${incident.resolvedAt.toISOString()}` : null,
    "",
    "Symptoms / Alert",
    "-".repeat(20),
    incident.rawAlert || incident.errorSignature || incident.alertType || "n/a",
    "",
    "Historical evidence (from analysis)",
    "-".repeat(20),
  ];

  const similar =
    (withMem?.similarIncidents as { incidentId?: string; rootCause?: string; resolution?: string }[]) ||
    [];
  if (similar.length === 0) {
    lines.push("No historical incidents recorded in analysis.");
  } else {
    for (const s of similar) {
      lines.push(`- ${s.incidentId}: ${s.rootCause || ""} → ${s.resolution || ""}`);
    }
  }

  if (incident.resolution) {
    lines.push(
      "",
      "Root cause",
      "-".repeat(20),
      incident.resolution.rootCause,
      "",
      "Successful resolution",
      "-".repeat(20),
      incident.resolution.successfulSteps || "n/a",
      "",
      `Runbook: ${incident.resolution.runbook || "n/a"}`,
      `Duration: ${incident.resolution.durationMinutes ?? "n/a"} minutes`,
      `Feedback: ${incident.resolution.feedback || "n/a"}`,
      `Feedback rating: ${(incident.resolution as { feedbackRating?: string }).feedbackRating || "n/a"}`,
      `Preventive actions: ${incident.resolution.preventiveActions || "n/a"}`
    );
  }

  lines.push(
    "",
    "Timeline",
    "-".repeat(20),
    ...incident.events.map(
      (e) =>
        `${e.timestamp.toISOString()}  [${e.eventType}] ${e.content}`
    ),
    "",
    "Memory operations",
    "-".repeat(20),
    ...incident.memoryOps.map(
      (o) =>
        `${o.createdAt.toISOString()}  ${o.operationType} ${o.status} ${o.summary || ""}`
    ),
    "",
    "Generated by OpsHindsight — advisory only",
  );

  const body = lines.filter((l) => l !== null).join("\n");
  return new NextResponse(body, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": `attachment; filename="postmortem-${incident.externalId}.txt"`,
    },
  });
}
